"""Conda plugin (T-P6-CONDA; FORMATS.md "Conda"): channels for proxy and hosted repositories.

Routes under ``/repository/<repo>/`` (the channel URL; conda: ``channels: [<base>/repository/<repo>]``):

- ``channeldata.json``: metadata (proxy: revalidated after the metadata max age; hosted: generated by the worker).
- ``<subdir>/repodata.json`` (``.zst``, ``.bz2``), ``current_repodata.json``, ``repodata_from_packages.json``
  (and their encodings): the subdir's listing.
- ``<subdir>/<name>-<version>-<build>.conda|.tar.bz2``: package files.
- ``<subdir>/repodata.jlap``, sharded repodata: 404 without an upstream request (clients fall back to the full file).

**Proxy**: repodata files can be hundreds of megabytes (conda-forge ``linux-64``), so they are streamed and cached
like content (tee to the client and the blob store, bounded by ``MAX_REPODATA``) and revalidated with the upstream's
``ETag``/``Last-Modified`` once older than the repository's metadata max age, as Maven snapshots are. After a
repodata file is stored it is scanned in the background (``waystation_common.conda.repodata``: streamed, bounded
memory) and its entries written to ``conda_packages`` (``sha256``/``md5``, ``size``) and ``conda_names`` (browse,
search). A package file is verified against its listing before it is committed; one requested before any indexed
listing names it is served and recorded ``unverified`` (its computed hash), and checked when a listing arrives (a
mismatch drops the cached copy), as apt pool files are.

**Hosted** (``formats.conda.hosted``): ``PUT``/``DELETE <subdir>/<file>``; repodata is generated by the worker.
"""

from __future__ import annotations

import asyncio
import logging
from collections import OrderedDict
from pathlib import Path
from typing import Any

from starlette.responses import JSONResponse, Response

from waystation_common.conda import PackageFile, sort_string
from waystation_common.conda import repodata as repodata_mod
from waystation_common.conda.repodata import Entry, RepodataError, Scan, compression_of
from waystation_common.db import conda as conda_db
from waystation_common.errors import NotFound
from waystation_server.db import assets as assets_db
from waystation_server.formats.base import FormatDescriptor, FormatRequest, WarmContext
from waystation_server.formats.conda import prefetch
from waystation_server.formats.conda.browse import CondaBrowse
from waystation_server.formats.conda.common import (
    CHANNELDATA,
    JSON_TYPE,
    PACKAGE_TYPE,
    REPODATA_FILES,
    SAFE_HEADERS,
    Op,
    Route,
    parse_route,
    repodata_type,
)
from waystation_server.formats.conda.descriptor import DESCRIPTOR
from waystation_server.formats.conda.hosted import CondaHosted
from waystation_server.problems import native_error
from waystation_server.proxy.engine import (
    AssetKind,
    AssetSpec,
    Expected,
    OnStored,
    ProxyEngine,
    StoredAsset,
)
from waystation_server.repos.model import RepoType

log = logging.getLogger('waystation.formats.conda')

MAX_CHANNELDATA = 128 * 1024 * 1024
MAX_REPODATA = 1024 * 1024 * 1024
BATCH = 1000
INDEXED = 256  # (repository, repodata blob) pairs remembered as indexed


def _scan_batch(entries: Any, sorts: dict[str, str], stats: dict[str, conda_db.NameStat]) -> list[Entry] | None:
    """The next batch of entries (in a thread), with the version sort keys and per-name statistics updated."""
    batch = next(entries, None)
    if batch is None:
        return None
    for entry in batch:
        key = sorts.get(entry.version)
        if key is None:
            key = sorts[entry.version] = sort_string(entry.version)
            if len(sorts) > 200_000:
                sorts.clear()
                sorts[entry.version] = key
        stat = stats.get(entry.name)
        if stat is None:
            stats[entry.name] = conda_db.NameStat(entry.version, key, 1)
        else:
            stat.files += 1
            if key > stat.latest_sort:
                stat.latest, stat.latest_sort = entry.version, key
    return list(batch)


class CondaPlugin:
    def __init__(self, descriptor: FormatDescriptor = DESCRIPTOR) -> None:
        self.descriptor = descriptor
        self.browser = CondaBrowse()
        self.hosted = CondaHosted()
        self._tasks: dict[tuple[str, str], asyncio.Task[None]] = {}
        self._indexed: OrderedDict[tuple[str, str], None] = OrderedDict()

    async def drain(self) -> None:
        """Wait for background indexing (tests, shutdown)."""
        while self._tasks:
            await asyncio.gather(*list(self._tasks.values()), return_exceptions=True)

    async def warm(self, ctx: WarmContext, item: str) -> None:
        """Prefetch (T-O12): ``formats.conda.prefetch``."""
        await prefetch.warm(ctx, item)

    async def handle(self, req: FormatRequest) -> Response:
        route = parse_route(req.path)
        if route is None or req.repo.type is RepoType.GROUP:
            raise NotFound('Not Found')
        req.log(op=route.op.value)
        if route.op is Op.RESOLVE:
            if req.prefetch is None or req.method != 'GET':
                raise NotFound('Not Found')
            return await self.resolve(req, route)
        if req.repo.type is RepoType.HOSTED:
            return await self.hosted.handle(req, route)
        if req.method not in ('GET', 'HEAD'):
            return native_error(405, 'this repository is a read-only proxy', headers={'Allow': 'GET, HEAD'})
        if req.repo.proxy is None or route.op is Op.UNSUPPORTED:
            raise NotFound('Not Found')
        match route.op:
            case Op.CHANNELDATA:
                spec = self.channeldata_spec()
            case Op.REPODATA:
                spec = self.repodata_spec(req, route.subdir, route.name)
            case _:
                assert route.package is not None
                spec = self.package_spec(req, route.subdir, route.package)
        response = await req.proxy.serve(req, spec)
        response.headers.update(SAFE_HEADERS)
        return response

    # ------------------------------------------------------------------ metadata
    @staticmethod
    def channeldata_spec() -> AssetSpec:
        return AssetSpec(
            path=CHANNELDATA,
            kind=AssetKind.METADATA,
            content_type=JSON_TYPE,
            max_size=MAX_CHANNELDATA,
            artifact=CHANNELDATA,
        )

    def repodata_spec(self, req: FormatRequest, subdir: str, filename: str) -> AssetSpec:
        proxy = req.repo.proxy
        max_age = proxy.metadata_max_age_s if proxy is not None else None
        if req.prefetch == 'refresh':
            max_age = 0
        return AssetSpec(
            path=f'{subdir}/{filename}',
            kind=AssetKind.CONTENT,
            content_type=repodata_type(filename),
            max_size=MAX_REPODATA,
            max_age_s=max_age,
            on_stored=self._on_repodata(req.proxy, req.repo.id, subdir),
            artifact=f'{subdir}/{filename}',
        )

    def _on_repodata(self, engine: ProxyEngine, repo_id: str, subdir: str) -> OnStored:
        async def stored(asset: StoredAsset, data: bytes | None) -> None:
            self.schedule(engine, repo_id, subdir, asset)

        return stored

    def schedule(self, engine: ProxyEngine, repo_id: str, subdir: str, asset: StoredAsset) -> asyncio.Task[None] | None:
        """Index a cached repodata file in the background (once per blob); the running task, if any."""
        key = (repo_id, asset.blob_sha256)
        running = self._tasks.get(key)
        if running is not None:
            return running
        if key in self._indexed:
            return None
        task = asyncio.create_task(self._index(engine, repo_id, subdir, asset))
        self._tasks[key] = task
        task.add_done_callback(lambda _: self._tasks.pop(key, None))
        return task

    async def _index(self, engine: ProxyEngine, repo_id: str, subdir: str, asset: StoredAsset) -> None:
        key = (repo_id, asset.blob_sha256)
        path: Path = engine.blobs.blob_path(asset.blob_sha256)
        result = Scan()
        entries = repodata_mod.batches(repodata_mod.read_entries(path, compression_of(asset.path), result), BATCH)
        sorts: dict[str, str] = {}
        stats: dict[str, conda_db.NameStat] = {}
        dropped: list[str] = []
        try:
            while True:
                batch = await asyncio.to_thread(_scan_batch, entries, sorts, stats)
                if batch is None:
                    break
                dropped += await conda_db.record_listing(engine.db, repo_id, subdir, batch, sorts=sorts)
            await conda_db.record_names(engine.db, repo_id, subdir, stats)
        except RepodataError as exc:
            log.warning('repodata not indexed', extra={'path': asset.path, 'error': str(exc)})
            return
        except Exception as exc:
            log.warning('repodata indexing failed', extra={'path': asset.path, 'error': type(exc).__name__})
            return
        self._indexed[key] = None
        while len(self._indexed) > INDEXED:
            self._indexed.popitem(last=False)
        for filename in dropped:
            log.warning('cached package does not match its listing; dropped', extra={'path': f'{subdir}/{filename}'})
        log.info(
            'indexed repodata',
            extra={'path': asset.path, 'entries': result.entries - result.skipped, 'skipped': result.skipped},
        )

    async def ensure_indexed(self, req: FormatRequest, subdir: str, *, wait: bool) -> None:
        """Index the subdir's cached repodata files that were not indexed by this process (a restart, a failure);
        with ``wait``, until done."""
        tasks = []
        for filename in sorted(REPODATA_FILES):
            asset = await assets_db.get(req.proxy.db, req.repo.id, f'{subdir}/{filename}')
            if asset is not None and filename.startswith('repodata'):
                task = self.schedule(req.proxy, req.repo.id, subdir, asset)
                if task is not None:
                    tasks.append(task)
        if wait and tasks:
            await asyncio.gather(*tasks, return_exceptions=True)

    # ------------------------------------------------------------------ packages
    def package_spec(self, req: FormatRequest, subdir: str, package: PackageFile) -> AssetSpec:
        engine, repo_id, filename = req.proxy, req.repo.id, package.filename
        found: dict[str, conda_db.FileRecord | None] = {}

        async def expect() -> Expected | None:
            record = await conda_db.lookup(engine.db, repo_id, subdir, filename)
            found['record'] = record
            if record is not None and record.verified:
                return Expected(sha256=record.sha256, md5=None if record.sha256 else record.md5, size=record.size)
            await self.ensure_indexed(req, subdir, wait=False)
            log.info('package not listed in any indexed repodata; serving unverified', extra={'path': req.path})
            return None

        async def stored(asset: StoredAsset, data: bytes | None) -> None:
            record = found.get('record')
            if record is not None and record.verified:
                return
            fields = {
                'name': package.name,
                'version': package.version,
                'build': package.build,
                'build_number': 0,
                'version_sort': sort_string(package.version),
                'timestamp': None,
            }
            listed = await conda_db.record_unverified(
                engine.db, repo_id, subdir, filename, fields, asset.blob_sha256, asset.size
            )
            if listed is not None and (
                (listed.sha256 is not None and listed.sha256 != asset.blob_sha256)
                or (listed.size is not None and listed.size != asset.size)
            ):
                log.warning('package does not match its listing; dropped', extra={'path': asset.path})
                await conda_db.drop_cached(engine.db, repo_id, asset.path, sha256=asset.blob_sha256)

        return AssetSpec(
            path=f'{subdir}/{filename}',
            kind=AssetKind.CONTENT,
            expect=expect,
            content_type=PACKAGE_TYPE,
            on_stored=stored,
            artifact=filename,
            component=f'{package.name} {package.version}',
        )

    # ------------------------------------------------------------------ prefetch
    async def resolve(self, req: FormatRequest, route: Route) -> Response:
        """``_ws/files/<subdir>/<name>/<version|->/<build|->`` (prefetch requests only): the matching file names of
        the subdir's listing, once its cached repodata is indexed."""
        if req.repo.type is RepoType.PROXY:
            await self.ensure_indexed(req, route.subdir, wait=True)
        docs = await conda_db.matching(req.proxy.db, req.repo.id, route.subdir, route.name, route.version, route.build)
        return JSONResponse({'files': [str(d['filename']) for d in docs]})
