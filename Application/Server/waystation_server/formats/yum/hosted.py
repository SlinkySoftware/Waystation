"""Hosted yum repositories (T-P5-YUMH; FORMATS.md "yum / dnf"; SPECIFICATION §4.2).

- **Upload**: ``PUT /repository/<repo>/<path>.rpm`` (``curl --upload-file``; stored at that path) or
  ``POST /repository/<repo>/[<dir>/]`` with the package as the body (stored as
  ``<dir>/<name>-<version>-<release>.<arch>.rpm``). The body is streamed into the blob store (bounded by
  ``WAYSTATION_MAX_UPLOAD_GB``, hard quota checked first), then the RPM header is read in a thread
  (``formats.yum.rpm``: bounded, offsets checked, header digest verified) for name, epoch, version, release,
  architecture, dependencies and files. Binary and source RPMs are accepted.
- **Write policy**: ``allow_redeploy`` replaces the package at a path, ``disable_redeploy`` refuses an existing path
  (409), ``read_only`` refuses every change (403). The same name-epoch-version-release-architecture at another path
  is refused (409) whatever the policy: dnf would see the package twice.
- **Delete**: ``DELETE <path>.rpm``.
- **Repodata**: each upload or delete writes the package's ``yum_packages`` record (with its ``primary``,
  ``filelists`` and ``other`` XML entries) and an ``index.yum`` job into the outbox in one MongoDB transaction; a
  worker rebuilds ``repodata/`` and signs ``repomd.xml`` with the repository's key (``waystation_worker.yum``),
  usually within seconds. The public key is served as ``RPM-GPG-KEY`` (and ``repodata/repomd.xml.key``). Until the
  first build ``repodata/repomd.xml`` answers 404.

Uploads need ``write``, deletes ``delete`` (the router checked them from the method); both are audited
(``content.upload`` / ``content.delete``) and shown in the activity feed. Groups are not supported for yum.
"""

from __future__ import annotations

import asyncio
import gzip
import json
import time
from datetime import UTC, datetime
from typing import Any

from starlette.responses import JSONResponse, Response

from waystation_common.db.client import Session
from waystation_common.errors import Conflict, Forbidden, NotFound, PayloadTooLarge, ValidationFailed
from waystation_common.events import CacheState, EventType
from waystation_common.jobs import YumIndex
from waystation_common.paths import normalise
from waystation_common.storage import BlobRef
from waystation_server import audit
from waystation_server.audit import AuditAction
from waystation_server.db import yum as yum_db
from waystation_server.formats.base import FormatRequest
from waystation_server.formats.yum import evr, rpm
from waystation_server.problems import native_error
from waystation_server.repos.model import RepoConfig, StoredHosted, WritePolicy

RPM_TYPE = 'application/x-rpm'
META_MAX = 8 * 1024 * 1024  # compressed repodata entries of one package (a document must stay well under 16 MiB)


def _meta(header: rpm.Header, *, href: str, sha256: str, size: int, upload_time: int) -> bytes:
    entries = rpm.entries(header, href=href, sha256=sha256, size=size, upload_time=upload_time)
    raw = json.dumps({'primary': entries.primary, 'filelists': entries.filelists, 'other': entries.other}).encode()
    packed = gzip.compress(raw, mtime=0)
    if len(packed) > META_MAX:
        raise PayloadTooLarge('the package lists too many files or too much metadata')
    return packed


def _check_path(path: str) -> None:
    if path == 'repodata' or path.startswith('repodata/'):
        raise ValidationFailed('packages cannot be stored under repodata/ (generated by Waystation)')


class YumHosted:
    async def handle(self, req: FormatRequest) -> Response:
        method, path = req.method, req.path
        if method in ('GET', 'HEAD'):
            return await self.get(req)
        if method == 'PUT' and path.endswith('.rpm'):
            return await self.upload(req, path)
        if method == 'POST' and not path.endswith('.rpm'):
            return await self.upload(req, None)
        if method == 'DELETE' and path.endswith('.rpm'):
            return await self.delete(req)
        return native_error(405, 'Method Not Allowed', headers={'Allow': 'GET, HEAD, PUT, POST, DELETE'})

    # ------------------------------------------------------------------ reading
    async def get(self, req: FormatRequest) -> Response:
        asset = await req.hosted.get(req.repo, req.path) if req.path else None
        if asset is not None:
            return req.hosted.serve(req, asset)
        req.hosted.account(req, CacheState.HIT, 404, 0, time.perf_counter())
        raise NotFound('Not Found')

    # ------------------------------------------------------------------ writing
    @staticmethod
    def _policy(req: FormatRequest) -> StoredHosted:
        hosted = req.repo.hosted or StoredHosted()
        if hosted.write_policy is WritePolicy.READ_ONLY:
            raise Forbidden('this repository is read-only')
        return hosted

    @staticmethod
    def _length(req: FormatRequest) -> int | None:
        length = req.request.headers.get('content-length')
        return int(length) if length is not None and length.isdigit() else None

    async def upload(self, req: FormatRequest, path: str | None) -> Response:
        hosted = self._policy(req)
        _check_path(path or f'{req.path.strip("/")}/x.rpm'.lstrip('/'))
        total = self._length(req)
        await req.hosted.admit(req.repo, total)  # a hard quota refuses before any byte is accepted (507)
        artifact = (path or 'package.rpm').rsplit('/', 1)[-1]
        async with await req.hosted.blobs.open_writer(expected_size=total) as writer:
            await req.hosted.receive(req, writer, path=path or req.path, artifact=artifact, total=total)
            ref = await req.hosted.blobs.commit(writer)
        header = await asyncio.to_thread(rpm.read_header, req.hosted.blobs.blob_path(ref.sha256))
        if path is None:
            directory = req.path.strip('/')
            path = normalise(f'{directory}/{header.filename}' if directory else header.filename)
        _check_path(path)
        db, repo = req.hosted.db, req.repo
        existing = await yum_db.hosted_by_path(db, repo.id, path)
        if existing is not None and hosted.write_policy is WritePolicy.DISABLE_REDEPLOY:
            raise Conflict(f'{path} exists and this repository does not allow redeploying')
        twin = await yum_db.hosted_by_nevra(
            db, repo.id, header.name, header.epoch, header.version, header.release, header.arch
        )
        if twin is not None and twin['path'] != path:
            raise Conflict(f'{header.filename} is already in this repository at {twin["path"]}')
        uploaded = datetime.now(UTC)
        meta = await asyncio.to_thread(
            _meta, header, href=path, sha256=ref.sha256, size=ref.size, upload_time=int(uploaded.timestamp())
        )
        await self.save(req, repo, path, header, ref, meta, uploaded)
        nevra = f'{header.name}-{evr.evr_string(header.epoch, header.version, header.release)}.{header.arch}'
        audit.record(
            AuditAction.CONTENT_UPLOAD,
            target=audit.target('yum_package', None, f'{repo.name}/{nevra}'),
            details={
                'repository': repo.name,
                'package': header.name,
                'version': evr.evr_string(header.epoch, header.version, header.release),
                'arch': header.arch,
                'path': path,
                'size': ref.size,
                'sha256': ref.sha256,
                'replaced': existing is not None,
            },
        )
        req.hosted.activity(req, EventType.ASSET_CREATED, path=path, artifact=header.filename, size=ref.size)
        req.hosted.account(req, CacheState.HIT, 201, 0, time.perf_counter())
        headers = {'ETag': f'"sha256:{ref.sha256}"', 'X-Checksum-Sha256': ref.sha256, 'Location': path}
        body = {'saved': True, 'path': path, 'name': header.name, 'evr': nevra.removeprefix(f'{header.name}-')}
        return JSONResponse(body, status_code=201, headers=headers)

    async def save(
        self,
        req: FormatRequest,
        repo: RepoConfig,
        path: str,
        header: rpm.Header,
        ref: BlobRef,
        meta: bytes,
        uploaded: datetime,
    ) -> None:
        """Record the package file, then its ``yum_packages`` entry and the index job in one transaction."""
        await req.hosted.record(repo, path, ref, content_type=RPM_TYPE)
        record: dict[str, Any] = {
            'path': path,
            'algorithm': 'sha256',
            'digest': ref.sha256,
            'size': ref.size,
            'name': header.name,
            'epoch': header.epoch,
            'version': header.version,
            'release': header.release,
            'arch': header.arch,
            'version_sort': evr.evr_key(header.epoch, header.version, header.release),
            'summary': header.summary[:500],
            'uploaded_at': uploaded,
            'uploaded_by': req.principal.display,
            'meta': meta,  # stored as BSON binary
        }

        async def write(session: Session) -> None:
            await yum_db.save_hosted(req.hosted.db, repo.id, record, session=session)
            await self._reindex(req, repo, session)

        await req.hosted.transaction(write)

    @staticmethod
    async def _reindex(req: FormatRequest, repo: RepoConfig, session: Session) -> None:
        if req.hosted.jobs is not None:
            await req.hosted.jobs.enqueue_durable(YumIndex(repo_id=repo.id), session=session)

    async def delete(self, req: FormatRequest) -> Response:
        self._policy(req)
        db, repo = req.hosted.db, req.repo
        found = await yum_db.hosted_by_path(db, repo.id, req.path)
        if found is None:
            raise NotFound('Not Found')

        async def write(session: Session) -> None:
            await yum_db.delete_hosted(db, repo.id, req.path, session=session)
            await self._reindex(req, repo, session)

        await req.hosted.transaction(write)
        removed = await req.hosted.remove(repo, req.path)
        size = removed.size if removed is not None else found.get('size')
        version = evr.evr_string(found.get('epoch'), str(found.get('version')), str(found.get('release')))
        audit.record(
            AuditAction.CONTENT_DELETE,
            target=audit.target('yum_package', None, f'{repo.name}/{found["name"]}-{version}.{found["arch"]}'),
            details={
                'repository': repo.name,
                'package': found['name'],
                'version': version,
                'path': req.path,
                'size': size,
            },
        )
        req.hosted.activity(
            req, EventType.ASSET_DELETED, path=req.path, artifact=req.path.rsplit('/', 1)[-1], size=size
        )
        req.hosted.account(req, CacheState.HIT, 204, 0, time.perf_counter())
        return Response(status_code=204)
