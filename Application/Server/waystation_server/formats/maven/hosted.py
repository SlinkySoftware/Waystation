CHECKSUM_MAX_BYTES = 4096


class Refused(WaystationError):  # noqa: N818 - reads as an outcome
    code = 'refused'
    status = 400


class ReadOnly(WaystationError):  # noqa: N818
    code = 'read_only'
    status = 403


def _stamp(when: datetime) -> str:
    return when.astimezone(UTC).strftime('%Y%m%d%H%M%S')


@dataclass(frozen=True)
class StoredFile:
    path: str
    updated_at: datetime


def snapshot_metadata(group_id: str, artifact_id: str, version: str, files: list[StoredFile]) -> md.Metadata | None:
    """The SNAPSHOT version-level document for the files of the version directory (None when it holds none)."""
    newest: dict[tuple[str, str], tuple[tuple[str, int], md.SnapshotVersion]] = {}
    plain: dict[tuple[str, str], md.SnapshotVersion] = {}
    latest: tuple[str, int] | None = None
    last_updated = ''
    for f in files:
        if coords.split_checksum(f.path) is not None:
            continue
        artifact = coords.parse_artifact(f.path)
        if artifact is None or artifact.version != version:
            continue
        key = (artifact.classifier or '', artifact.extension)
        stamp = artifact.timestamp
        last_updated = max(last_updated, _stamp(f.updated_at))
        if stamp is None:
            plain[key] = md.SnapshotVersion(artifact.classifier, artifact.extension, version, _stamp(f.updated_at))
            continue
        updated = stamp[0].replace('.', '')
        entry = md.SnapshotVersion(artifact.classifier, artifact.extension, artifact.file_version, updated)
        if key not in newest or newest[key][0] < stamp:
            newest[key] = (stamp, entry)
        if latest is None or latest < stamp:
            latest = stamp
    if not newest and not plain:
        return None
    entries = {**plain, **{k: v[1] for k, v in newest.items()}}
    return md.Metadata(
        group_id=group_id,
        artifact_id=artifact_id,
        version=version,
        last_updated=last_updated,
        snapshot_timestamp=latest[0] if latest else None,
        snapshot_build=latest[1] if latest else None,
        local_copy=latest is None,
        snapshot_versions=[entries[k] for k in sorted(entries)],
    )


class MavenHosted:
    def __init__(self, digests: Digests) -> None:
        self.digests = digests

    async def handle(self, req: FormatRequest) -> Response:
        match req.method:
            case 'GET' | 'HEAD':
                return await self.get(req)
            case 'PUT':
                return await self.put(req)
            case 'DELETE':
                return await self.delete(req)
        return native_error(405, 'Method Not Allowed', headers={'Allow': 'GET, HEAD, PUT, DELETE'})

    # ------------------------------------------------------------------ reads
    async def get(self, req: FormatRequest) -> Response:
        path = req.path
        if not path or req.request.url.path.endswith('/'):
            raise NotFound('Not Found')
        started = time.perf_counter()
        split = coords.split_checksum(path)
        if split is not None:
            base, alg = split
            asset = await req.hosted.get(req.repo, base)
            if asset is None:
                raise NotFound('Not Found')
            digest = await self.digests.of(asset, alg, req.hosted.blobs.blob_path(asset.blob_sha256))
            response = generated(req.request, digest.encode(), 'text/plain')
            sent = len(digest) if response.status_code == 200 and req.method == 'GET' else 0
            req.hosted.account(req, CacheState.HIT, response.status_code, sent, started)
            return response
        asset = await req.hosted.get(req.repo, path)
        if asset is None:
            raise NotFound('Not Found')
        return req.hosted.serve(req, asset)

    # ------------------------------------------------------------------ writes
    @staticmethod
    def _writable(req: FormatRequest) -> StoredHosted:
        hosted = req.repo.hosted or StoredHosted()
        if hosted.write_policy is WritePolicy.READ_ONLY:
            raise ReadOnly('this repository is read-only')
        return hosted

    async def put(self, req: FormatRequest) -> Response:
        hosted = self._writable(req)
        path = req.path
        if not path or req.request.url.path.endswith('/'):
            raise Refused('a file path is required')
        options = options_of(req.repo)
        if options.layout_policy == 'strict' and not coords.strict_ok(path):
            raise Refused(f'{path} is not a Maven repository layout path')
        version = coords.version_of_path(path)
        if not policy_allows(options, version):
            kind = 'SNAPSHOT' if version and is_snapshot(version) else 'release'
            raise Refused(
                f'this repository ({options.version_policy} version policy) does not accept {kind} version {version}'
            )
        split = coords.split_checksum(path)
        if split is not None:
            return await self._put_checksum(req, *split)
        if coords.is_metadata(path):
            return await self._put_metadata(req, path)
        return await self._put_file(req, path, hosted)

    async def _read_body(self, req: FormatRequest, limit: int) -> bytes:
        body = bytearray()
        async for chunk in req.request.stream():
            body += chunk
            if len(body) > limit:
                raise PayloadTooLarge(f'limited to {limit} bytes')
        return bytes(body)

    async def _put_checksum(self, req: FormatRequest, base: str, alg: str) -> Response:
        data = await self._read_body(req, CHECKSUM_MAX_BYTES)
        if coords.is_metadata(base):
            return Response(status_code=201)
        given = coords.parse_checksum(data, alg)
        if given is None:
            raise Refused(f'not a {alg} checksum')
        asset = await req.hosted.get(req.repo, base)
        if asset is not None:
            digest = await self.digests.of(asset, alg, req.hosted.blobs.blob_path(asset.blob_sha256))
            if digest != given:
                raise Refused(f'the {alg} checksum does not match the stored {base.rsplit("/", 1)[-1]}')
        return Response(status_code=201)

    async def _put_metadata(self, req: FormatRequest, path: str) -> Response:
        data = await self._read_body(req, md.MAX_BYTES)
        try:
            parsed = await asyncio.to_thread(md.parse, data)
        except ValidationFailed as exc:
            raise Refused(exc.detail) from None
        where = coords.parse_metadata_path(path)
        assert where is not None
        snapshot = where.snapshot_version
        if snapshot is not None:
            await self.regenerate(req, snapshot[0], snapshot[1], snapshot[2])
        elif parsed.artifact_id is not None and where.ga is not None:
            await self.regenerate(req, where.ga[0], where.ga[1], None)
        else:
            await self._store_plugins(req, path, parsed)
        return Response(status_code=201)

    async def _store_plugins(self, req: FormatRequest, path: str, parsed: md.Metadata) -> None:
        """A groupId-level document (plugin prefixes): merged with the stored one under the directory's lock."""
        directory = path[: -len(coords.METADATA)].rstrip('/')
        async with artifact_lock(req.proxy.valkey, req.repo.id, directory, ''):
            current = await req.hosted.get(req.repo, path)
            documents = [parsed]
            if current is not None:
                with contextlib.suppress(ValidationFailed, ValueError):
                    documents.insert(0, md.parse(await req.hosted.read(current, max_bytes=md.MAX_BYTES)))
            merged = md.merge(documents)
            merged.group_id = merged.group_id or (directory.replace('/', '.') or None)
            await self._write_document(req.repo, req, path, md.render(merged))

    async def _put_file(self, req: FormatRequest, path: str, hosted: StoredHosted) -> Response:
        started = time.perf_counter()
        artifact = coords.parse_artifact(path)
        snapshot = artifact is not None and artifact.snapshot
        existing = await req.hosted.get(req.repo, path)
        if existing is not None and not snapshot and hosted.write_policy is not WritePolicy.ALLOW_REDEPLOY:
            raise Refused(f'{path.rsplit("/", 1)[-1]} already exists and this repository does not allow redeploying')
        length = req.request.headers.get('content-length')
        total = int(length) if length is not None and length.isdigit() else None
        await req.hosted.admit(req.repo, total)
        name = path.rsplit('/', 1)[-1]
        component = f'{artifact.group_id}:{artifact.artifact_id}:{artifact.version}' if artifact else None
        async with await req.hosted.blobs.open_writer(expected_size=total) as writer:
            try:
                await req.hosted.receive(req, writer, path=path, artifact=name, component=component, total=total)
            except UploadInterrupted as exc:
                raise Refused(exc.detail) from None
            ref = await req.hosted.blobs.commit(writer)
        await req.hosted.record(req.repo, path, ref, content_type=coords.content_type(path))
        if artifact is not None:
            await maven_db.upsert_version(
                req.hosted.db,
                req.repo.id,
                artifact.group_id,
                artifact.artifact_id,
                artifact.version,
                version_sort=sort_key(artifact.version),
                uploaded_by=req.principal.display,
            )
            await self.regenerate(
                req, artifact.group_id, artifact.artifact_id, artifact.version if artifact.snapshot else None
            )
        details: dict[str, Any] = {'repository': req.repo.name, 'path': path, 'size': ref.size, 'sha256': ref.sha256}
        if artifact is not None:
            details |= {'group_id': artifact.group_id, 'artifact_id': artifact.artifact_id, 'version': artifact.version}
        audit.record(
            AuditAction.CONTENT_UPLOAD,
            target=audit.target('maven_file', ref.sha256, f'{req.repo.name}/{path}'),
            details=details,
        )
        req.hosted.activity(req, EventType.ASSET_CREATED, path=path, artifact=component or name, size=ref.size)
        req.hosted.account(req, CacheState.HIT, 201, 0, started)
        req.log(component=component)
        return Response(status_code=201)

    # ------------------------------------------------------------------ metadata regeneration
    async def regenerate(self, req: FormatRequest, group_id: str, artifact_id: str, snapshot: str | None) -> None:
        """Rewrite the groupId/artifactId document (and the SNAPSHOT version's, when given) from what the repository
        holds now, serialised per artifact across replicas."""
        repo = req.repo
        ga = f'{group_id.replace(".", "/")}/{artifact_id}'
        async with artifact_lock(req.proxy.valkey, repo.id, group_id, artifact_id):
            if snapshot is not None:
                folder = f'{ga}/{snapshot}/'
                docs = await maven_db.files_under(req.hosted.db, repo.id, folder)
                files = [StoredFile(str(d['path']), d.get('updated_at') or d['created_at']) for d in docs]
                document = snapshot_metadata(group_id, artifact_id, snapshot, files)
                path = folder + coords.METADATA
                if document is None:
                    await req.hosted.remove(repo, path)
                else:
                    await self._write_document(repo, req, path, md.render(document))
            versions = await maven_db.versions(req.hosted.db, repo.id, group_id, artifact_id)
            path = f'{ga}/{coords.METADATA}'
            if not versions:
                await req.hosted.remove(repo, path)
                return
            document = md.versions_metadata(group_id, artifact_id, versions, _stamp(datetime.now(UTC)))
            await self._write_document(repo, req, path, md.render(document))

    @staticmethod
    async def _write_document(repo: RepoConfig, req: FormatRequest, path: str, data: bytes) -> None:
        async with await req.hosted.blobs.open_writer(max_size=md.MAX_BYTES) as writer:
            await writer.write(data)
            ref = await req.hosted.blobs.commit(writer)
        await req.hosted.record(repo, path, ref, content_type=XML_TYPE, kind=AssetKind.METADATA)

    # ------------------------------------------------------------------ deletes
    async def delete(self, req: FormatRequest) -> Response:
        self._writable(req)
        started = time.perf_counter()
        path = req.path
        if not path:
            raise NotFound('Not Found')
        if req.request.url.path.endswith('/'):
            return await self._delete_folder(req, path, started)
        if coords.split_checksum(path) is not None or coords.is_metadata(path):
            raise Refused('checksum files and maven-metadata.xml are maintained by the server')
        removed = await req.hosted.remove(req.repo, path)
        if removed is None:
            raise NotFound('Not Found')
        artifact = coords.parse_artifact(path)
        if artifact is not None:
            await self._version_gone_check(req, artifact.group_id, artifact.artifact_id, artifact.version)
        self._deleted(req, path, removed.size, started)
        return Response(status_code=204)

    async def _delete_folder(self, req: FormatRequest, path: str, started: float) -> Response:
        """``DELETE <g>/<a>/<v>/``: every file of a version."""
        segments = path.split('/')
        artifact = coords.parse_artifact(f'{path}/{segments[-2] if len(segments) > 1 else ""}-{segments[-1]}.pom')
        if artifact is None:
            raise Refused('only version folders can be deleted (groupId/artifactId/version/)')
        folder = path + '/'
        files = await maven_db.files_under(req.hosted.db, req.repo.id, folder)
        if not files:
            raise NotFound('Not Found')
        size = 0
        for doc in files:
            removed = await req.hosted.remove(req.repo, str(doc['path']))
            size += removed.size if removed is not None else 0
        await self._version_gone_check(req, artifact.group_id, artifact.artifact_id, artifact.version)
        self._deleted(req, folder, size, started)
        return Response(status_code=204)

    async def _version_gone_check(self, req: FormatRequest, group_id: str, artifact_id: str, version: str) -> None:
        folder = f'{group_id.replace(".", "/")}/{artifact_id}/{version}/'
        remaining = await maven_db.files_under(req.hosted.db, req.repo.id, folder, limit=50)
        if not any(
            coords.parse_artifact(str(d['path'])) is not None
            for d in remaining
            if not coords.is_metadata(str(d['path']))
        ):
            await maven_db.remove_version(req.hosted.db, req.repo.id, group_id, artifact_id, version)
        await self.regenerate(req, group_id, artifact_id, version if is_snapshot(version) else None)

    @staticmethod
    def _deleted(req: FormatRequest, path: str, size: int, started: float) -> None:
        audit.record(
            AuditAction.CONTENT_DELETE,
            target=audit.target('maven_file', None, f'{req.repo.name}/{path}'),
            details={'repository': req.repo.name, 'path': path, 'size': size},
        )
        req.hosted.activity(req, EventType.ASSET_DELETED, path=path, artifact=path.rstrip('/').rsplit('/', 1)[-1])
        req.hosted.account(req, CacheState.HIT, 204, 0, started)
