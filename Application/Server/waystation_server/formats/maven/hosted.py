"""Maven hosted repositories (FORMATS.md "Maven"; SPECIFICATION §4.2): ``mvn deploy``, Gradle ``maven-publish``,
curl ``PUT``.

- **Artifacts** (``PUT <g>/<a>/<v>/<file>``): streamed into the blob store as a live upload (hard quota checked
  first), recorded as an asset, the version recorded as a component. Refused with ``400``: a path that is not a Maven
  layout path when the layout policy is strict (permissive: any normalised path), a version the version policy does
  not admit (SNAPSHOT into a release repository and the reverse), a release file that already exists when the write
  policy is not ``allow_redeploy``. SNAPSHOT versions may always be redeployed. ``read_only`` refuses every write.
- **Checksum files** are not stored: they are generated from the stored file's digests on ``GET``. An uploaded one is
  compared with the stored file (``400`` when it differs); a checksum of a ``maven-metadata.xml`` is accepted and
  ignored (the server's document differs from the client's).
- **maven-metadata.xml** is regenerated by the server after every deploy and delete, serialised per groupId and
  artifactId (``common.artifact_lock``): the groupId/artifactId document lists every version of the repository in
  Maven order (``latest`` the highest, ``release`` the highest release), a SNAPSHOT version's document names its
  newest timestamped build per classifier and extension. Uploaded documents of those two levels are validated and
  discarded; a groupId-level document (Maven plugin prefixes) is stored, its plugins merged with the stored ones.
- **Deletes**: a file, or a whole version directory (``DELETE <g>/<a>/<v>/``); the metadata is regenerated.

Uploads and deletes are audited (``content.upload`` / ``content.delete``) and shown in the activity feed, once per
file (checksums and metadata documents excluded).
"""

