"""Test helpers: build Alpine apk v2 packages and signed ``APKINDEX.tar.gz`` files the way abuild does (gzip
segments: signature, control without end-of-archive, data)."""

from __future__ import annotations

import hashlib
import io
import tarfile
import zlib

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import padding, rsa

from waystation_common import apk


def _gzip(data: bytes) -> bytes:
    compressor = zlib.compressobj(9, zlib.DEFLATED, 31)
    return compressor.compress(data) + compressor.flush()


def _tar(files: dict[str, bytes], *, end: bool) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode='w', format=tarfile.PAX_FORMAT) as tar:
        for name, data in files.items():
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mtime = 1_700_000_000
            tar.addfile(info, io.BytesIO(data))
    raw = buf.getvalue()
    if end:
        return raw
    # abuild-tar --cut: drop the end-of-archive blocks (and tarfile's record padding)
    while raw.endswith(b'\0' * 512):
        raw = raw[:-512]
    return raw


def make_key() -> rsa.RSAPrivateKey:
    return rsa.generate_private_key(public_exponent=65537, key_size=2048)


def sign_segment(data: bytes, key: rsa.RSAPrivateKey, key_name: str, *, sha256: bool = False) -> bytes:
    algorithm: hashes.HashAlgorithm = hashes.SHA256() if sha256 else hashes.SHA1()
    signature = key.sign(data, padding.PKCS1v15(), algorithm)
    kind = 'RSA256' if sha256 else 'RSA'
    return _gzip(_tar({f'.SIGN.{kind}.{key_name}': signature}, end=False))


def build_apk(
    name: str,
    version: str,
    arch: str = 'x86_64',
    *,
    description: str = 'test package',
    depends: tuple[str, ...] = (),
    files: dict[str, bytes] | None = None,
    key: rsa.RSAPrivateKey | None = None,
    key_name: str = 'test.rsa.pub',
    datahash: bool = True,
    extra: str = '',
) -> bytes:
    """A v2 ``.apk`` (signed when ``key`` is given)."""
    data = _gzip(_tar(files or {f'usr/share/{name}/README': f'{name} {version}\n'.encode()}, end=True))
    lines = [
        '# Generated by tests',
        f'pkgname = {name}',
        f'pkgver = {version}',
        f'pkgdesc = {description}',
        'url = https://example.com/',
        'builddate = 1700000000',
        'size = 4096',
        f'arch = {arch}',
        'origin = ' + name,
        'license = MIT',
        *(f'depend = {d}' for d in depends),
    ]
    if datahash:
        lines.append(f'datahash = {hashlib.sha256(data).hexdigest()}')
    pkginfo = ('\n'.join(lines) + '\n' + extra).encode()
    control = _gzip(_tar({'.PKGINFO': pkginfo}, end=False))
    signature = sign_segment(control, key, key_name) if key is not None else b''
    return signature + control + data


def checksum(package: bytes) -> str:
    info = apk.read_package(io.BytesIO(package), len(package))
    return info.checksum


def build_index(
    packages: dict[str, bytes], *, key: rsa.RSAPrivateKey | None = None, key_name: str = 'test.rsa.pub'
) -> bytes:
    """An ``APKINDEX.tar.gz`` listing ``packages`` (file name -> bytes), signed (SHA-1, as Alpine) when ``key``."""
    stanzas = []
    for package in packages.values():
        info = apk.read_package(io.BytesIO(package), len(package))
        stanzas.append(apk.stanza(info, arch=info.arch if info.arch != 'noarch' else 'x86_64'))
    text = '\n'.join(stanzas)
    index = _gzip(_tar({'DESCRIPTION': b'test index', 'APKINDEX': text.encode()}, end=True))
    return (sign_segment(index, key, key_name) if key is not None else b'') + index
