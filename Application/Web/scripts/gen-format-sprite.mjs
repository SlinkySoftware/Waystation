// Regenerates src/assets/formats.svg (the format icon sprite) and src/components/brandMarks.ts from an unpacked
// simple-icons package (CC0). Run in the dev image from Application/Web:
//   npm pack simple-icons@16 && tar xzf simple-icons-*.tgz && node scripts/gen-format-sprite.mjs 16.37.0 package
import fs from 'node:fs'

const version = process.argv[2] ?? 'unknown'
const pkg = process.argv[3] ?? 'package'
const slugs = {
  docker: 'docker', npm: 'npm', debian: 'debian', ubuntu: 'ubuntu', raspberrypi: 'raspberrypi', redhat: 'redhat',
  rockylinux: 'rockylinux', almalinux: 'almalinux', fedora: 'fedora', pypi: 'pypi', maven: 'apachemaven', go: 'go',
  helm: 'helm', terraform: 'terraform', opentofu: 'opentofu', ansible: 'ansible', swift: 'swift', nuget: 'nuget',
  cargo: 'rust', rubygems: 'rubygems', composer: 'composer', conda: 'anaconda', alpine: 'alpinelinux',
  huggingface: 'huggingface',
}
// Material Symbols "package_2" (Apache-2.0) for raw/generic files.
const RAW = 'M440-183v-274L200-596v274l240 139Zm80 0 240-139v-274L520-457v274Zm-80 92L160-252q-19-11-29.5-29T120-321v-318q0-22 10.5-40t29.5-29l280-161q19-11 40-11t40 11l280 161q19 11 29.5 29t10.5 40v318q0 22-10.5 40T800-252L520-91q-19 11-40 11t-40-11Zm200-528 77-44-237-137-78 45 238 136Zm-160 93 78-45-237-137-78 45 237 137Z'

const data = JSON.parse(fs.readFileSync(`${pkg}/data/simple-icons.json`, 'utf8'))
const list = Array.isArray(data) ? data : data.icons
const norm = (t) =>
  t.toLowerCase().replace(/\+/g, 'plus').replace(/\./g, 'dot').replace(/&/g, 'and').normalize('NFD').replace(/[^a-z0-9]/g, '')

let svg = `<svg xmlns="http://www.w3.org/2000/svg">
<!-- Waystation format sprite. Brand marks from Simple Icons ${version} (CC0-1.0, https://simpleicons.org);
     marks remain trademarks of their owners. "raw" is Material Symbols package_2 (Apache-2.0).
     Generated by scripts/gen-format-sprite.mjs; do not hand-edit. -->
`
let ts = `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated with assets/formats.svg (scripts/gen-format-sprite.mjs): titles and brand colours of the sprite symbols.

export const brandMarks = {
`
for (const [key, slug] of Object.entries(slugs)) {
  const file = fs.readFileSync(`${pkg}/icons/${slug}.svg`, 'utf8')
  const title = file.match(/<title>(.*?)<\/title>/)[1]
  const path = file.match(/ d="([^"]+)"/)[1]
  const meta = list.find((i) => (i.slug ?? norm(i.title)) === slug)
  svg += `<symbol id="${key}" viewBox="0 0 24 24"><path d="${path}"/></symbol>\n`
  ts += `  ${key}: { title: '${title.replace(/'/g, "\\'")}', hex: '#${meta.hex}' },\n`
}
svg += `<symbol id="raw" viewBox="0 -960 960 960"><path d="${RAW}"/></symbol>\n</svg>\n`
ts += `  raw: { title: 'Raw', hex: '#0f766e' },
} as const

export type BrandMark = keyof typeof brandMarks
`
fs.writeFileSync('src/assets/formats.svg', svg)
fs.writeFileSync('src/components/brandMarks.ts', ts)
