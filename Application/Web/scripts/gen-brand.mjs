// Brand assets (UI_DESIGN §8), generated from src/assets/brand/geometry.ts so the component, the master SVGs and
// the favicon set never drift. Run in the dev image (`make brand`; `make brand-check` fails if the committed SVGs
// or the manifest are stale). Writes:
//   src/assets/brand/  master SVGs: mark (light, dark, mono, 16 px), wordmark, lockup (light, dark), app tile
//   public/            favicon.svg (follows the browser theme), favicon-16/32/48.png, favicon.ico,
//                      apple-touch-icon.png, icon-192/512.png, icon-maskable-512.png, manifest.webmanifest
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { COLORS, MARK, MARK_SMALL, WORDMARK } from '../src/assets/brand/geometry.ts'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const BRAND = join(ROOT, 'src/assets/brand')
const PUBLIC = join(ROOT, 'public')
const check = process.argv.includes('--check')
const HEADER = '<!-- Waystation brand (GPL-3.0-or-later). Generated by scripts/gen-brand.mjs from src/assets/brand/geometry.ts; do not hand-edit. -->'

/** The mark's shapes; `marker` and `glyph` are fill/stroke paint (or class names when `classes` is set). */
function markShapes({ marker, glyph, classes = false, mark = MARK }) {
  const paint = (p) => (classes ? `class="${p}"` : `fill="${p}" stroke="${p}"`)
  const strokePaint = (p) => (classes ? `class="${p} l"` : `fill="none" stroke="${p}"`)
  return [
    `<path ${paint(marker)} stroke-width="${mark.markerStroke}" stroke-linejoin="round" d="${mark.marker}"/>`,
    `<path ${paint(glyph)} stroke-width="${mark.slabStroke}" stroke-linejoin="round" d="${mark.slab}"/>`,
    `<path ${strokePaint(glyph)} stroke-width="${mark.layerStroke}" stroke-linecap="round" stroke-linejoin="round" d="${mark.layers.join('')}"/>`,
  ].join('')
}

/** Monochrome mark: the marker in currentColor (or `paint`) with the glyph cut out, so any background shows through. */
function monoShapes(paint = 'currentColor', id = 'ws-cut') {
  return (
    `<mask id="${id}" maskUnits="userSpaceOnUse" x="0" y="0" width="32" height="32"><rect width="32" height="32" fill="#fff"/>` +
    markShapes({ marker: '#fff', glyph: '#000' }).replace(/^<path[^>]*\/>/, '') +
    `</mask><path fill="${paint}" stroke="${paint}" stroke-width="${MARK.markerStroke}" stroke-linejoin="round" mask="url(#${id})" d="${MARK.marker}"/>`
  )
}

const svg = (viewBox, body, title = 'Waystation') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${title}">${HEADER}${body}</svg>\n`

function wordmarkShapes(paint) {
  return (
    `<g fill="none" stroke="${paint}" stroke-width="${WORDMARK.stroke}" stroke-linecap="round" stroke-linejoin="round">` +
    WORDMARK.paths.map((d) => `<path d="${d}"/>`).join('') +
    `</g><circle fill="${paint}" cx="${WORDMARK.dot.cx}" cy="${WORDMARK.dot.cy}" r="${WORDMARK.dot.r}"/>`
  )
}

/** Mark (scaled to the wordmark's x-height band) followed by the wordmark. */
function lockup(marker, glyph, ink) {
  const scale = 1.3
  const gap = 10
  const markW = 32 * scale
  const width = markW + gap + WORDMARK.width
  // Centre the mark on the x-height band (y 20-40), where the eye reads the word.
  const markY = 30 - 16 * scale
  return svg(
    `0 ${WORDMARK.top} ${width} ${WORDMARK.height}`,
    `<g transform="translate(0 ${markY}) scale(${scale})">${markShapes({ marker, glyph })}</g>` +
      `<g transform="translate(${markW + gap} 0)">${wordmarkShapes(ink)}</g>`,
  )
}

/** Square app tile: brand background, the mark in white with the glyph showing the brand colour. */
function tile(markScale) {
  const size = 512
  const s = (size * markScale) / 32
  const off = (size - 32 * s) / 2
  return svg(
    `0 0 ${size} ${size}`,
    `<rect width="${size}" height="${size}" fill="${COLORS.brand}"/>` +
      `<g transform="translate(${off} ${off + s * 0.5}) scale(${s})">${markShapes({ marker: COLORS.onBrand, glyph: COLORS.brand })}</g>`,
  )
}

const favicon = svg(
  MARK.viewBox,
  `<style>.m{fill:${COLORS.brand};stroke:${COLORS.brand}}.g{fill:${COLORS.onBrand};stroke:${COLORS.onBrand}}.l{fill:none}` +
    `@media (prefers-color-scheme:dark){.m{fill:${COLORS.brandDark};stroke:${COLORS.brandDark}}.g{fill:${COLORS.onBrandDark};stroke:${COLORS.onBrandDark}}.l{fill:none}}</style>` +
    markShapes({ marker: 'm', glyph: 'g', classes: true, mark: MARK_SMALL }),
)

const masters = {
  'mark.svg': svg(MARK.viewBox, markShapes({ marker: COLORS.brand, glyph: COLORS.onBrand })),
  'mark-dark.svg': svg(MARK.viewBox, markShapes({ marker: COLORS.brandDark, glyph: COLORS.onBrandDark })),
  'mark-mono.svg': svg(MARK.viewBox, monoShapes()),
  'mark-small.svg': svg(MARK.viewBox, markShapes({ marker: COLORS.brand, glyph: COLORS.onBrand, mark: MARK_SMALL })),
  'wordmark.svg': svg(`0 ${WORDMARK.top} ${WORDMARK.width} ${WORDMARK.height}`, wordmarkShapes('currentColor')),
  'lockup.svg': lockup(COLORS.brand, COLORS.onBrand, COLORS.ink),
  'lockup-dark.svg': lockup(COLORS.brandDark, COLORS.onBrandDark, '#ffffff'),
  'app-tile.svg': tile(0.62),
}

const manifest =
  JSON.stringify(
    {
      name: 'Waystation',
      short_name: 'Waystation',
      description: 'Every package, one stop.',
      start_url: './',
      scope: './',
      display: 'standalone',
      theme_color: COLORS.brand,
      background_color: '#f5f6f8',
      icons: [
        { src: 'favicon.svg', sizes: 'any', type: 'image/svg+xml' },
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
        { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2,
  ) + '\n'

const text = {
  ...Object.fromEntries(Object.entries(masters).map(([name, body]) => [join(BRAND, name), body])),
  [join(PUBLIC, 'favicon.svg')]: favicon,
  [join(PUBLIC, 'manifest.webmanifest')]: manifest,
}

if (check) {
  const stale = Object.entries(text).filter(([path, body]) => {
    try {
      return readFileSync(path, 'utf8') !== body
    } catch {
      return true
    }
  })
  if (stale.length) {
    console.error(`Brand assets are stale (run make brand):\n  ${stale.map(([p]) => p.slice(ROOT.length + 1)).join('\n  ')}`)
    process.exit(1)
  }
  console.log('Brand assets are up to date.')
  process.exit(0)
}

for (const [path, body] of Object.entries(text)) writeFileSync(path, body)

// Raster set. resvg renders the SVGs above; the favicons use the light mark (tab strips are mostly light, and the
// teal reads on dark ones too) with the 16 px-tuned glyph at 16, the touch and maskable icons use the opaque tile.
const { Resvg } = await import('@resvg/resvg-js')
const png = (source, size) => Buffer.from(new Resvg(source, { fitTo: { mode: 'width', value: size } }).render().asPng())
const transparent = { 16: 'favicon-16.png', 32: 'favicon-32.png', 48: 'favicon-48.png', 192: 'icon-192.png', 512: 'icon-512.png' }
const rendered = {}
for (const [size, name] of Object.entries(transparent)) {
  rendered[size] = png(masters[size === '16' ? 'mark-small.svg' : 'mark.svg'], Number(size))
  writeFileSync(join(PUBLIC, name), rendered[size])
}
// Apple touch icons are shown opaque with their own rounded corners: the full-bleed tile.
writeFileSync(join(PUBLIC, 'apple-touch-icon.png'), png(tile(0.66), 180))
// Maskable: the mark inside the 80% safe zone (platforms crop to circles, squircles, ...).
writeFileSync(join(PUBLIC, 'icon-maskable-512.png'), png(tile(0.56), 512))

// favicon.ico: PNG-compressed entries (16, 32, 48), supported by every current browser.
const sizes = [16, 32, 48]
const header = Buffer.alloc(6 + 16 * sizes.length)
header.writeUInt16LE(0, 0)
header.writeUInt16LE(1, 2)
header.writeUInt16LE(sizes.length, 4)
let offset = header.length
sizes.forEach((size, i) => {
  const e = 6 + 16 * i
  header.writeUInt8(size, e)
  header.writeUInt8(size, e + 1)
  header.writeUInt16LE(1, e + 4)
  header.writeUInt16LE(32, e + 6)
  header.writeUInt32LE(rendered[size].length, e + 8)
  header.writeUInt32LE(offset, e + 12)
  offset += rendered[size].length
})
writeFileSync(join(PUBLIC, 'favicon.ico'), Buffer.concat([header, ...sizes.map((s) => rendered[s])]))
console.log(`Wrote ${Object.keys(text).length} SVG/manifest files and ${Object.keys(transparent).length + 3} raster icons.`)
