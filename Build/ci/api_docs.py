"""Static REST API reference (``make api-docs``; SPECIFICATION §7).

Builds the server's OpenAPI document from the app factory (no database, no network: the same document the server
serves at ``/api/v1/openapi.json``) and renders it into ``Documents/API/``:

- ``openapi.json``: the document itself (keys sorted, ``info.version`` = the API version ``v1``), for tools;
- ``REFERENCE.md``: every operation grouped by tag (parameters, request body, responses) and every schema.

``--check`` exits 1 when the committed files differ from what the current code generates (CI, ``make
api-docs-check``; the unit test ``test_api_docs.py`` checks the same). Stdlib plus the server package.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

OUT_DIR = Path('Documents/API')
JSON_FILE = 'openapi.json'
MD_FILE = 'REFERENCE.md'
API_VERSION = 'v1'
METHODS = ('get', 'head', 'post', 'put', 'patch', 'delete')
REF_PREFIX = '#/components/schemas/'

HEADER = """\
# Waystation REST API reference ({version})

<!-- Generated by `make api-docs` (Build/ci/api_docs.py) from the server's OpenAPI document. Do not edit. -->

Every operation of the REST API under `/api/v1`, generated from the server's own OpenAPI 3.1 document (also in
[`openapi.json`](openapi.json) next to this file, and served by a running server at `/api/v1/openapi.json`).
Authentication, errors, paging and the event stream are described in [README.md](README.md).

{count} operations in {tags} groups; {schemas} schemas.

"""


def build_document() -> dict[str, Any]:
    """The server's OpenAPI document, built from the app factory without starting it."""
    from waystation_server.app import create_app  # server import only when generating

    doc: dict[str, Any] = create_app().openapi()
    doc['info'] = {**doc.get('info', {}), 'version': API_VERSION}
    return doc


def _anchor(name: str) -> str:
    return 'schema-' + ''.join(c if c.isalnum() else '-' for c in name).lower()


def _op_anchor(method: str, path: str) -> str:
    return 'op-' + method + ''.join(c if c.isalnum() else '-' for c in path).lower().rstrip('-')


def _cell(text: Any) -> str:
    return ' '.join(str(text).split()).replace('|', '\\|')


def type_of(schema: dict[str, Any] | bool | None) -> str:
    """A short Markdown rendering of a JSON Schema type, linking named schemas."""
    if schema is None or schema is True or schema == {}:
        return 'any'
    if schema is False:
        return 'never'
    if '$ref' in schema:
        name = schema['$ref'].removeprefix(REF_PREFIX)
        return f'[`{name}`](#{_anchor(name)})'
    if 'const' in schema:
        return f'`{json.dumps(schema["const"])}`'
    if 'enum' in schema:
        return ' \\| '.join(f'`{json.dumps(v)}`' for v in schema['enum'])
    for key in ('anyOf', 'oneOf', 'allOf'):
        if key in schema:
            parts = [p for p in schema[key] if p != {'type': 'null'}]
            joiner = ' & ' if key == 'allOf' else ' \\| '
            text = joiner.join(type_of(p) for p in parts)
            return text + (' \\| null' if len(parts) < len(schema[key]) else '')
    kind = schema.get('type')
    if isinstance(kind, list):
        return ' \\| '.join(type_of({**schema, 'type': k}) for k in kind)
    if kind == 'array':
        return f'array of {type_of(schema.get("items"))}'
    if kind == 'object' or 'properties' in schema:
        extra = schema.get('additionalProperties')
        if 'properties' not in schema and isinstance(extra, dict):
            return f'object of {type_of(extra)}'
        return 'object'
    if kind is None:
        return 'any'
    fmt = schema.get('format')
    return f'{kind} ({fmt})' if fmt else str(kind)


def _constraints(schema: dict[str, Any]) -> str:
    keys = (
        'minimum',
        'maximum',
        'exclusiveMinimum',
        'exclusiveMaximum',
        'minLength',
        'maxLength',
        'pattern',
        'minItems',
        'maxItems',
        'default',
    )
    for sub in schema.get('anyOf', []):
        if sub.get('type') != 'null':
            schema = {**sub, **{k: v for k, v in schema.items() if k == 'default'}}
            break
    found = [f'{k}: `{json.dumps(schema[k])}`' for k in keys if k in schema]
    return '; '.join(found)


def _describe(schema: dict[str, Any]) -> str:
    text = _cell(schema.get('description', ''))
    extra = _constraints(schema)
    return f'{text} ({extra})' if text and extra else text or extra


def _content(content: dict[str, Any]) -> list[str]:
    return [f'`{media}` {type_of(body.get("schema"))}' for media, body in sorted(content.items())]


def render_operation(method: str, path: str, op: dict[str, Any]) -> list[str]:
    lines = [f'<a id="{_op_anchor(method, path)}"></a>', f'### `{method.upper()} {path}`', '']
    if op.get('summary'):
        lines += [f'**{_cell(op["summary"])}**' + (' (deprecated)' if op.get('deprecated') else ''), '']
    if op.get('description'):
        lines += [op['description'].strip(), '']
    params = op.get('parameters', [])
    if params:
        lines += ['| Parameter | In | Type | Required | Description |', '|---|---|---|---|---|']
        for p in params:
            schema = p.get('schema', {})
            desc = _describe({**schema, 'description': p.get('description', schema.get('description', ''))})
            req = 'yes' if p.get('required') else 'no'
            lines.append(f'| `{p["name"]}` | {p["in"]} | {type_of(schema)} | {req} | {desc} |')
        lines.append('')
    body = op.get('requestBody')
    if body:
        req = 'required' if body.get('required') else 'optional'
        lines += [f'Request body ({req}): ' + ', '.join(_content(body.get('content', {}))), '']
    lines += ['| Status | Description | Body |', '|---|---|---|']
    for status, resp in sorted(op.get('responses', {}).items()):
        body_text = ', '.join(_content(resp.get('content', {}))) or '-'
        lines.append(f'| {status} | {_cell(resp.get("description", ""))} | {body_text} |')
    lines.append('')
    return lines


def render_schema(name: str, schema: dict[str, Any]) -> list[str]:
    lines = [f'<a id="{_anchor(name)}"></a>', f'### `{name}`', '']
    if schema.get('description'):
        lines += [_cell(schema['description']), '']
    props = schema.get('properties')
    if props:
        required = set(schema.get('required', []))
        lines += ['| Field | Type | Required | Description |', '|---|---|---|---|']
        for field, sub in props.items():
            flags = [f for f in ('readOnly', 'writeOnly') if sub.get(f)]
            desc = _describe(sub) + (f' ({", ".join(flags)})' if flags else '')
            lines.append(f'| `{field}` | {type_of(sub)} | {"yes" if field in required else "no"} | {desc} |')
        lines.append('')
    else:
        lines += [f'Type: {type_of(schema)}', '']
    return lines


def render_markdown(doc: dict[str, Any]) -> str:
    groups: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, item in sorted(doc.get('paths', {}).items()):
        for method in METHODS:
            if method in item:
                op = item[method]
                groups.setdefault((op.get('tags') or ['other'])[0], []).append((method, path, op))
    schemas = doc.get('components', {}).get('schemas', {})
    count = sum(len(ops) for ops in groups.values())
    out = [HEADER.format(version=API_VERSION, count=count, tags=len(groups), schemas=len(schemas)).rstrip('\n'), '']
    out += ['## Contents', '']
    for tag in sorted(groups):
        out.append(f'- [{tag}](#group-{_anchor(tag)[7:]}) ({len(groups[tag])})')
    out += ['- [Schemas](#schemas)', '']
    for tag in sorted(groups):
        out += [f'<a id="group-{_anchor(tag)[7:]}"></a>', f'## {tag}', '']
        for method, path, _ in groups[tag]:
            out.append(f'- [`{method.upper()} {path}`](#{_op_anchor(method, path)})')
        out.append('')
        for method, path, op in groups[tag]:
            out += render_operation(method, path, op)
    out += ['<a id="schemas"></a>', '## Schemas', '']
    for name in sorted(schemas):
        out += render_schema(name, schemas[name])
    return '\n'.join(out).rstrip('\n') + '\n'


def render(doc: dict[str, Any]) -> dict[str, str]:
    """File name → content, as committed under ``Documents/API/``."""
    return {
        JSON_FILE: json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + '\n',
        MD_FILE: render_markdown(doc),
    }


def stale_files(out_dir: Path, files: dict[str, str]) -> list[str]:
    stale = []
    for name, content in files.items():
        path = out_dir / name
        if not path.is_file() or path.read_text(encoding='utf-8') != content:
            stale.append(str(path))
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail if the committed reference is stale')
    parser.add_argument('--out', type=Path, default=OUT_DIR)
    args = parser.parse_args(argv)
    files = render(build_document())
    if args.check:
        stale = stale_files(args.out, files)
        if stale:
            print('API reference is stale (run `make api-docs` and commit): ' + ', '.join(stale), file=sys.stderr)
            return 1
        print('API reference is up to date.')
        return 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (args.out / name).write_text(content, encoding='utf-8')
        print(f'Wrote {args.out / name}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
