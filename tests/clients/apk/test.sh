#!/bin/sh
# Alpine apk through Waystation (client-alpine: Alpine 3.22, apk-tools, curl, GNU tar, abuild-tar).
# 1. Proxy: /etc/apk/repositories points at the proxy of the Alpine CDN (credentials in the URL); apk update verifies
#    the APKINDEX passed through untouched with the image's Alpine keys; apk add installs a tiny package that Waystation
#    verified against the index C: checksum (control segment SHA-1, then the data segment through .PKGINFO datahash).
# 2. Hosted: a package is assembled as abuild does (abuild-tar --hash/--cut, datahash; unsigned), uploaded with
#    curl; the worker publishes an APKINDEX signed with the repository's RSA key (.SIGN.RSA256.<key name>); apk refuses
#    it until the key the repository serves is in /etc/apk/keys, then installs it, upgrades to a second upload and no
#    longer offers a deleted version.
set -eu
. /harness/lib.sh

W=$WAYSTATION_URL
HOST=${W#*://}
ARCH=$(apk --print-arch)
work=/tmp/apk-harness
rm -rf "$work"
mkdir -p "$work"
cp /etc/apk/repositories "$work/repositories.orig"

step 'API token for the repositories'
ws_login
ws_token '["read", "write", "delete"]' '["alpine-proxy", "apk-hosted"]'
token=$WS_TOKEN
auth="admin:$token"

repositories() {  # repositories <repository> <branch>/<repo>: /etc/apk/repositories with one line, token included
  printf 'http://admin:%s@%s/repository/%s/%s\n' "$token" "$HOST" "$1" "$2" > /etc/apk/repositories
}

step "apk update and apk add through the proxy (v3.22/main, $ARCH)"
repositories alpine-proxy v3.22/main
apk update > "$work/update.log" 2>&1 || { cat "$work/update.log"; fail 'apk update through the proxy'; }
if grep -qi 'untrusted\|error' "$work/update.log"; then cat "$work/update.log"; fail 'apk update reported an error'; fi
apk add --no-progress tree > "$work/add.log" 2>&1 || { cat "$work/add.log"; fail 'apk add tree'; }
tree --version | grep -q '^tree' || fail 'tree does not run'

step 'a wrong token is refused'
printf 'http://admin:wrong@%s/repository/alpine-proxy/v3.22/main\n' "$HOST" > /etc/apk/repositories
if apk update > "$work/wrong.log" 2>&1 && ! grep -qi 'error\|unable\|denied\|unauthorized' "$work/wrong.log"; then
  cat "$work/wrong.log"; fail 'apk update with a wrong token succeeded'
fi

build() {  # build <version>: $work/ws-hello-<version>.apk (noarch, unsigned: trusted through the signed index)
  dir="$work/build-$1"
  rm -rf "$dir"
  mkdir -p "$dir/root/usr/share/ws-hello"
  echo "hello $1" > "$dir/root/usr/share/ws-hello/hello.txt"
  # as abuild does: POSIX tar, per-file checksums added by abuild-tar --hash
  (cd "$dir/root" && tar --format=posix -c usr | abuild-tar --hash | gzip -n -9 > "$dir/data.tar.gz") \
    || fail "tar data"
  datahash=$(sha256sum "$dir/data.tar.gz" | cut -d' ' -f1)
  cat > "$dir/.PKGINFO" <<PKGINFO
# Generated by the Waystation client harness
pkgname = ws-hello
pkgver = $1
pkgdesc = Waystation harness package
url = https://example.com/
builddate = 1700000000
size = 16
arch = noarch
origin = ws-hello
license = MIT
datahash = $datahash
PKGINFO
  # abuild-tar --cut: the control segment ends after its last member (no end-of-archive blocks)
  (cd "$dir" && tar --format=posix -c .PKGINFO | abuild-tar --cut | gzip -n -9 > control.tar.gz) || fail 'tar control'
  cat "$dir/control.tar.gz" "$dir/data.tar.gz" > "$work/ws-hello-$1.apk"
}

hosted="$W/repository/apk-hosted"
index="$hosted/v1/main/$ARCH/APKINDEX.tar.gz"
listed() {  # listed <version>: does the published APKINDEX list ws-hello <version>?
  curl -fsS -u "$auth" "$index" 2>/dev/null | gzip -dc 2>/dev/null | grep -aq "^V:$1\$"
}
wait_listed() {  # wait_listed <version> <yes|no>: until the worker published an index that does (not) list it
  i=0
  while :; do
    if listed "$1"; then [ "$2" = yes ] && return 0; else [ "$2" = no ] && return 0; fi
    i=$((i + 1)); [ "$i" -lt 60 ] || fail "the worker did not publish an APKINDEX (ws-hello $1 listed: $2)"; sleep 1
  done
}
upload() {  # upload <version>
  code=$(curl -sS -o "$work/upload.json" -w '%{http_code}' -u "$auth" --upload-file "$work/ws-hello-$1.apk" \
    "$hosted/v1/main/$ARCH/ws-hello-$1.apk")
  [ "$code" = 201 ] || fail "upload of ws-hello $1 returned $code: $(cat "$work/upload.json")"
}

step 'assemble ws-hello 1.0-r0 (abuild-tar) and upload it with curl'
build 1.0-r0
upload 1.0-r0
wait_listed 1.0-r0 yes

step 'apk refuses the hosted index until the repository key is trusted'
repositories apk-hosted v1/main
if apk update > "$work/untrusted.log" 2>&1 && ! grep -qi 'untrusted' "$work/untrusted.log"; then
  cat "$work/untrusted.log"; fail 'apk accepted an index signed by an unknown key'
fi

step 'trust the key the repository serves (/etc/apk/keys), apk update, apk add'
ws_api GET /repositories/apk-hosted/setup > "$work/setup.json" || fail 'no setup guide'
key=$(grep -o '/etc/apk/keys/[A-Za-z0-9._-]*\.rsa\.pub' "$work/setup.json" | head -n 1)
key=${key#/etc/apk/keys/}
[ -n "$key" ] || fail 'the setup guide names no key'
curl -fsS -u "$auth" -o "/etc/apk/keys/$key" "$hosted/keys/$key" || fail "no key at keys/$key"
grep -q 'BEGIN PUBLIC KEY' "/etc/apk/keys/$key" || fail 'the key is not a PEM public key'
apk update --force-refresh > "$work/hosted.log" 2>&1 || { cat "$work/hosted.log"; fail 'apk update (hosted)'; }
if grep -qi 'untrusted' "$work/hosted.log"; then cat "$work/hosted.log"; fail 'the hosted index is untrusted'; fi
apk add --no-progress ws-hello > "$work/add-hosted.log" 2>&1 || { cat "$work/add-hosted.log"; fail 'apk add ws-hello'; }
[ "$(cat /usr/share/ws-hello/hello.txt)" = 'hello 1.0-r0' ] || fail 'ws-hello 1.0-r0 not installed'

step 'a second version: upload, wait for the new index, apk upgrade'
build 1.1-r0
upload 1.1-r0
wait_listed 1.1-r0 yes
apk update --force-refresh > "$work/update2.log" 2>&1 || { cat "$work/update2.log"; fail 'apk update after the second upload'; }
apk upgrade --no-progress ws-hello > "$work/upgrade.log" 2>&1 || { cat "$work/upgrade.log"; fail 'apk upgrade'; }
if [ "$(cat /usr/share/ws-hello/hello.txt)" != 'hello 1.1-r0' ]; then
  cat "$work/update2.log" "$work/upgrade.log"
  fail 'ws-hello 1.1-r0 not installed'
fi

step 'browse API lists both versions, newest first'
ws_api GET '/repositories/apk-hosted/apk/versions?package=ws-hello' > "$work/versions.json" || fail 'no versions'
tr -d '\n' < "$work/versions.json" | grep -q '"version":"1.1-r0".*"version":"1.0-r0"' \
  || fail "versions not listed newest first: $(cat "$work/versions.json")"

step 'delete 1.0-r0 with curl; after the rebuild apk no longer offers it'
code=$(curl -sS -o /dev/null -w '%{http_code}' -u "$auth" -X DELETE "$hosted/v1/main/$ARCH/ws-hello-1.0-r0.apk")
[ "$code" = 204 ] || fail "delete returned $code"
wait_listed 1.0-r0 no
apk update --force-refresh > /dev/null 2>&1 || fail 'apk update after the delete'
if apk search -a -x ws-hello 2>/dev/null | grep -q 'ws-hello-1.0-r0'; then fail 'ws-hello 1.0-r0 still offered'; fi

step 'without credentials the hosted repository is not readable'
code=$(curl -sS -o /dev/null -w '%{http_code}' "$index")
case "$code" in 401 | 404) ;; *) fail "anonymous APKINDEX returned $code" ;; esac

cp "$work/repositories.orig" /etc/apk/repositories
pass
