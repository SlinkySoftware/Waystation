#!/usr/bin/env bash
# Real-client harness runner (tests/clients/README.md). Called by `make clients-test FORMAT=<f|all> MODE=<m>`.
#   tests/clients/run.sh <format|all> <replay|record|live>
# Host requirements: bash + docker only. Everything else runs in containers.
# Env: STACK=1 forces the Waystation stack up even when the format does not need it; KEEP=1 leaves the stack and
# the run directory in place after the run (inspect, then `docker compose -p <project> down -v`).
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
CLIENTS="$ROOT/tests/clients"
FIXTURES_ROOT="$ROOT/tests/fixtures/upstreams"
CHECKOUT_ID=$(printf '%s' "$ROOT" | md5sum | cut -c1-8)

usage() { echo "usage: $0 <format|all> <replay|record|live>" >&2; exit 2; }
[ $# -eq 2 ] || usage
FORMAT_ARG=$1
MODE=$2
case "$MODE" in replay|record|live) ;; *) usage ;; esac

formats() {
  local d
  for d in "$CLIENTS"/*/; do
    [ -f "$d/format.env" ] && basename "$d"
  done
}

check_fixtures() {  # check_fixtures <fixtures-root> <path>
  "$CLIENTS/check_fixtures.sh" --fixtures-root "$1" "$2"
}

run_format() (  # subshell: the EXIT trap tears down this format's project
  set -euo pipefail
  local fmt=$1
  local dir="$CLIENTS/$fmt"
  [ -f "$dir/format.env" ] || { echo "no such format: $fmt (expected $dir/format.env)" >&2; exit 2; }
  [ -f "$dir/test.sh" ] || { echo "$fmt: missing $dir/test.sh" >&2; exit 2; }

  # shellcheck disable=SC1091
  local HOSTS='' CLIENT='' NEEDS_STACK=0 ORIGINS='' RECORD_SERVICES=''
  # shellcheck source=/dev/null
  . "$dir/format.env"
  [ -n "$HOSTS" ] && [ -n "$CLIENT" ] || { echo "$fmt: format.env needs HOSTS and CLIENT" >&2; exit 2; }

  local project="waystation-harness-$CHECKOUT_ID-$fmt"
  local run_dir="$CLIENTS/.run/$fmt"
  local fixtures
  case "$MODE" in
    replay)
      fixtures="$FIXTURES_ROOT/$fmt"
      [ -d "$fixtures" ] || { echo "$fmt: no fixtures in $fixtures; record them: make clients-test FORMAT=$fmt MODE=record" >&2; exit 1; }
      ;;
    record) fixtures="$FIXTURES_ROOT/recordings-tmp/$fmt"; rm -rf "$fixtures"; mkdir -p "$fixtures" ;;
    live) fixtures="$run_dir/discard"; mkdir -p "$fixtures" ;;
  esac
  rm -rf "$run_dir/ca" "$run_dir/state"
  mkdir -p "$run_dir/ca" "$run_dir/state"

  local stack=0
  [ "${NEEDS_STACK:-0}" = 1 ] || [ "${STACK:-0}" = 1 ] && stack=1

  export HARNESS_PROJECT="$project" HARNESS_RUN_DIR="$run_dir" HARNESS_FIXTURES="$fixtures" HARNESS_MODE="$MODE"
  export HARNESS_FORMAT="$fmt" HARNESS_HOSTS="$HOSTS" HARNESS_ORIGINS="$ORIGINS" HARNESS_STACK="$stack"
  export HARNESS_UID HARNESS_GID HARNESS_CLIENTS_DIR="$CLIENTS"
  HARNESS_UID=$(id -u)
  HARNESS_GID=$(id -g)
  export WAYSTATION_IMAGE_PREFIX=waystation WAYSTATION_IMAGE_TAG=harness

  # Throwaway stack env (secrets are random per run and deleted with the run directory).
  umask 077
  {
    echo 'WAYSTATION_BASE_URL=http://waystation-web:8080'
    echo 'WAYSTATION_LOG_FORMAT=console'
    echo 'WAYSTATION_LOG_LEVEL=INFO'
    echo "WAYSTATION_SECRET_KEYS=$(head -c 32 /dev/urandom | base64)"
    echo "WAYSTATION_SESSION_SECRET=$(head -c 32 /dev/urandom | base64)"
  } > "$run_dir/stack.env"
  umask 022

  local compose=(docker compose -p "$project" --env-file "$run_dir/stack.env"
    -f "$ROOT/Build/Containers/compose.yaml" -f "$ROOT/Build/Containers/compose.dev.yaml"
    -f "$CLIENTS/compose.harness.yaml")

  cleanup() {
    local rc=$?
    if [ "${KEEP:-0}" = 1 ]; then
      echo "KEEP=1: left project $project and $run_dir in place"
    else
      "${compose[@]}" --profile clients --profile origins down -v --remove-orphans >/dev/null 2>&1 || true
      rm -rf "$run_dir"
    fi
    exit "$rc"
  }
  trap cleanup EXIT

  echo "==> $fmt: mode=$MODE project=$project stack=$stack"
  "${compose[@]}" up -d --build --quiet-build --wait --quiet-pull fake-upstream
  if [ "$MODE" != replay ] && [ -n "$RECORD_SERVICES" ]; then
    # shellcheck disable=SC2086
    "${compose[@]}" up -d --wait --quiet-pull $RECORD_SERVICES
  fi

  # Point every public upstream name at the fake upstream, for the clients and the server/worker.
  local ip
  ip=$(docker inspect -f "{{(index .NetworkSettings.Networks \"${project}_frontend\").IPAddress}}" "$project-fake-upstream")
  [ -n "$ip" ] || { echo "$fmt: could not find the fake upstream's address" >&2; exit 1; }
  local hosts_yaml="" h svc
  for h in $HOSTS; do hosts_yaml+="      - \"$h:$ip\""$'\n'; done
  {
    echo "# Generated by tests/clients/run.sh for $project; do not edit."
    echo 'services:'
    for svc in server worker; do
      echo "  $svc:"
      echo "    environment:"
      echo "      WAYSTATION_SSRF_ALLOW_CIDRS: \"$ip/32\""
      echo "    extra_hosts:"
      printf '%s' "$hosts_yaml"
    done
    for svc in curl node debian ubuntu skopeo docker; do
      echo "  client-$svc:"
      echo "    extra_hosts:"
      printf '%s' "$hosts_yaml"
    done
  } > "$run_dir/compose.hosts.yaml"
  compose+=(-f "$run_dir/compose.hosts.yaml")

  if [ "$stack" = 1 ]; then
    "${compose[@]}" up -d --build --quiet-build --wait --wait-timeout 300 --quiet-pull web server worker
  fi

  local rc=0
  "${compose[@]}" run --rm --no-deps --quiet-pull "client-$CLIENT" \
    sh -c 'set -eu; d=/harness/$HARNESS_FORMAT; if [ -f "$d/setup.sh" ]; then sh "$d/setup.sh"; fi; exec sh "$d/test.sh"' \
    || rc=$?

  if [ -s "$run_dir/state/misses.txt" ]; then
    echo "FAIL $fmt: the fake upstream reported misses/errors:" >&2
    sed 's/^/  /' "$run_dir/state/misses.txt" >&2
    rc=1
  fi
  if [ "$rc" != 0 ]; then
    echo "---- fake-upstream log (last 40 lines)" >&2
    "${compose[@]}" logs --no-log-prefix --tail 40 fake-upstream >&2 || true
    exit "$rc"
  fi

  if [ "$MODE" = record ]; then
    check_fixtures "$FIXTURES_ROOT/recordings-tmp" "$fixtures" \
      || { echo "$fmt: new recordings left in $fixtures (not installed)" >&2; exit 1; }
    rm -rf "${FIXTURES_ROOT:?}/$fmt"
    mv "$fixtures" "$FIXTURES_ROOT/$fmt"
    rmdir "$FIXTURES_ROOT/recordings-tmp" 2>/dev/null || true
    echo "==> $fmt: fixtures recorded into tests/fixtures/upstreams/$fmt ($(du -sb "$FIXTURES_ROOT/$fmt" | cut -f1) bytes)"
  fi
  echo "==> $fmt: PASS ($MODE)"
)

if [ "$FORMAT_ARG" = all ]; then
  mapfile -t selected < <(formats)
else
  selected=("$FORMAT_ARG")
fi
failed=()
for f in "${selected[@]}"; do
  set +e
  run_format "$f"
  rc=$?
  set -e
  [ "$rc" = 0 ] || failed+=("$f")
done
if [ ${#failed[@]} -gt 0 ]; then
  echo "clients-test FAILED ($MODE): ${failed[*]}" >&2
  exit 1
fi
echo "clients-test passed ($MODE): ${selected[*]}"
